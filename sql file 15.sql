#window functions
-- rank restaurants based on total revenue
select restaurant_name,sum(order_amount) as total_revenue,rank() over( order by sum(order_amount) desc) as ranking
from restaurants r join orders07 o
on r.restaurant_id=o.restaurant_id group by restaurant_name;

-- rank customers by spending
select customer_name,sum(order_amount) as spending,rank() over(order by sum(order_amount)desc) as ranking
from customers07 c join orders07 o on c.customer_id=o.customer_id
group by customer_name;

-- sequence numbers to orders placed by each customer
select customer_name,order_id,row_number() over (partition by c.customer_id order by order_id) as numbering
from customers07 c join orders07 o
on c.customer_id=o.customer_id ;

--  each customer current order with previous order amount
select c.customer_id,customer_name,order_id,order_amount,lag(order_amount) over(partition by c.customer_id) as previous
from customers07 c join orders07 o on c.customer_id=o.customer_id;

