lag(order_amount) over (partition by customer_id order by order_timestamp) as previous from orders07 o join customers07 c on c.customer_id=o.customer_id)
select customer_name,customer_id,order_amount,previous from new
where order_amount>previous;

-- restaurants with consistently above average revenue
