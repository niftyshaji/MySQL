 select c.customer_name,c.customer_id,order_id
 from customers07 c join orders07 o
 on c.customer_id=o.customer_id
 where order_id is null;
 
 -- restaurants and their corresponding orders
 select restaurant_name,order_id
 from restaurants r join orders07 o
 on r.restaurant_id=o.restaurant_id;
 
 -- total revenue generated by each restaurant
 select restaurant_name,sum(order_amount) as total_revenue
 from restaurants r join orders07 o
 on r.restaurant_id=o.restaurant_id
 group by restaurant_name;
 
 -- customer who spent highest amount overall
 select customer_name,sum(order_amount) as highest_amount
 from customers07 c join orders07 o
 on c.customer_id=o.customer_id
 group by customer_name
 order by sum(order_amount) desc limit 1;
 
 -- customers whose total spending is greater than average customer spending
 with customer_spending as
 (select customer_name,sum(order_amount) as total_spending
 from customers07 c join orders07 o on c.customer_id=o.customer_id
 group by customer_name)
 select customer_name,total_spending from customer_spending where total_spending>(select avg(total_spending) from customer_spending);
 
 -- restaurants earning more revenue than average restaurant revenue
 with restaurants_earning as
 (select restaurant_name,sum(order_amount) as total_revenue
 from restaurants r join orders07 o
 on r.restaurant_id=o.restaurant_id
 group by restaurant_name)
 select restaurant_name,total_revenue from restaurants_earning
 where total_revenue>(select avg(total_revenue) from restaurants_earning);
 
 -- delivery agents who completed more deliveries than average no of deliveries
 with delivery as
 (select agent_name,d.agent_id,count(order_id) as total_deliveries
