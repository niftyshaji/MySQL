 -- percentage contribution of each restaurant to total company revenue
with new as
(select restaurant_name,r.restaurant_id,sum(order_amount) as revenue
from restaurants r join orders07 o on r.restaurant_id=o.restaurant_id group by r.restaurant_id,restaurant_name)
select restaurant_name,restaurant_id,revenue,(revenue/(select sum(revenue)from new))*100 as percentage from new;

-- each restaurants revenue difference from the highest earning restaurant;
with new as
(select r.restaurant_name,r.restaurant_id,sum(order_amount) as revenue
from restaurants r join orders07 o on r.restaurant_id=o.restaurant_id group by r.restaurant_id)
select restaurant_name,restaurant_id,((select max(revenue) from new )-revenue) as revenue_difference from new;

-- current months revenue with previous months revenue
with monthly_revenue as
(select date_format(order_timestamp,'%Y-%M') as month,sum(order_amount) as revenue
from orders07 group by month),
new as
(select month,revenue,lag(revenue) over (order by month) as previous from monthly_revenue)
select revenue,previous,month,(revenue-previous/previous)*100 as growth from new;

-- first order placed by every customer
